#!/usr/bin/env node
// Type-count spike: build matchup webs for 4, 5, 6 and 8 types by folding the
// authored 8-type roster, solving each web against the folded creature kits,
// and emitting mock/matrices.js for the gallery page.
//
// Run: node tools/battle-matrices-spike.mjs
// Test: node --test tools/tests/battle-matrices-spike_test.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { WHEEL } from './battle-wheel.mjs';
import {
  chartFromEdges, solveWeb, unsatisfiedDemands, triangles, edgeList,
} from './battle-matchup-solver.mjs';

const repo = path.dirname(fileURLToPath(import.meta.url)) + '/..';
export const OUTPUT = 'mock/matrices.js';

// Successive folds of the authored 8 types. Every fold maps all eight base
// types onto the target order; gold names keep the base icon art.
export const FOLDS = {
  8: {
    label: '8 types — full web',
    order: WHEEL.order,
    map: Object.fromEntries(WHEEL.order.map((type) => [type, type])),
    seedEdges: WHEEL.edges,
  },
  6: {
    label: '6 types — lightning folds into fire, elder into spirit',
    order: ['spirit', 'water', 'wind', 'earth', 'fire', 'plant'],
    map: {
      spirit: 'spirit', elder: 'spirit',
      water: 'water', wind: 'wind', earth: 'earth',
      fire: 'fire', lightning: 'fire', plant: 'plant',
    },
    seedEdges: WHEEL.edges,
  },
  5: {
    label: '5 types — wind folds into water too',
    order: ['spirit', 'water', 'earth', 'fire', 'plant'],
    map: {
      spirit: 'spirit', elder: 'spirit',
      water: 'water', wind: 'water', earth: 'earth',
      fire: 'fire', lightning: 'fire', plant: 'plant',
    },
    seedEdges: WHEEL.edges,
  },
  4: {
    label: '4 types — flame / bloom / tide / stone cycle',
    order: ['flame', 'bloom', 'tide', 'stone'],
    map: {
      fire: 'flame', lightning: 'flame',
      plant: 'bloom', spirit: 'bloom',
      water: 'tide', wind: 'tide',
      earth: 'stone', elder: 'stone',
    },
    seedEdges: [
      ['fire', 'plant'], ['plant', 'water'], ['water', 'fire'],
      ['earth', 'lightning'], ['lightning', 'water'], ['water', 'earth'],
      ['fire', 'wind'], ['wind', 'earth'], ['earth', 'fire'],
      ['plant', 'spirit'], ['spirit', 'elder'], ['elder', 'plant'],
    ],
  },
};

function foldEdges(edges, map) {
  const folded = [];
  const seen = new Set();
  for (const [from, to] of edges) {
    const a = map[from], b = map[to];
    if (!a || !b || a === b) continue;
    const key = `${a}>${b}`, reverse = `${b}>${a}`;
    if (seen.has(key) || seen.has(reverse)) continue;
    seen.add(key);
    folded.push([a, b]);
  }
  return folded;
}

// Kits are the authored 8-type `moves` name list (CreatureGathererFX-4w89.6).
function foldSets(creatureList, map, order) {
  return creatureList.map((creature) => ({
    name: creature.name,
    types: [...new Set(creature.moves
      .map((type) => map[type])
      .filter((type) => type && order.includes(type)))],
  }));
}

export function buildMatrices() {
  const require = createRequire(import.meta.url);
  const data = require(path.join(repo, 'mock/data.js'));
  const matrices = [];
  for (const count of [8, 6, 5, 4]) {
    const fold = FOLDS[count];
    const seedEdges = foldEdges(fold.seedEdges, fold.map);
    const sets = foldSets(data.creatures, fold.map, fold.order);
    let seed = 4242 + count;
    const rng = () => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed / 0x7fffffff; };
    const solution = solveWeb(fold.order, seedEdges, sets, { attempts: 400, rng });
    if (solution.outstanding !== 0) {
      throw Error(`${count}-type web leaves ${solution.outstanding} unsatisfied demands`);
    }
    const chart = solution.chart;
    const edges = edgeList(fold.order, chart);
    const decisive = edges.length / (fold.order.length * (fold.order.length - 1));
    matrices.push({
      id: String(count),
      label: fold.label,
      order: fold.order,
      map: fold.map,
      edges,
      chart,
      stats: {
        types: fold.order.length,
        edges: edges.length,
        decisivePercent: Math.round(100 * decisive),
        triangles: triangles(fold.order, chart).length,
        neutralPercent: Math.round(100 * (1 - decisive)),
        demands: unsatisfiedDemands(fold.order, chart, sets).length === 0,
      },
    });
  }
  return { folds: FOLDS, matrices };
}

export function serializeMatrices(built) {
  return '// Generated by tools/battle-matrices-spike.mjs. Do not hand-edit.\n'
    + '// Type-count spike tables: 8/6/5/4 types folded from the authored roster.\n'
    + '(function (root) {\n'
    + '  const DATA = ' + JSON.stringify(built) + ';\n'
    + '  if (typeof module !== "undefined" && module.exports) module.exports = DATA;\n'
    + '  else root.CGFX_MATRICES = DATA;\n'
    + '})(typeof window !== "undefined" ? window : this);\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const built = buildMatrices();
  fs.writeFileSync(path.join(repo, OUTPUT), serializeMatrices(built));
  for (const matrix of built.matrices) {
    const s = matrix.stats;
    console.log(`${matrix.id} types: edges ${s.edges}, decisive ${s.decisivePercent}%, `
      + `neutral ${s.neutralPercent}%, triangles ${s.triangles}, demands met ${s.demands}`);
  }
  console.log(`PASS: wrote ${OUTPUT}`);
}
